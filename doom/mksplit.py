"""Write the linker script that splits Doom between flash (cold code, runs in place) and a fixed RAM address (everything hot).
Inputs: the relocatable build's map (out/doom/doom.map) and an emulator profile of the demo (EMU_PROFILE of that same build).
Rule: a CORE module (renderer, game logic, tables, zone, video, platform) stays in RAM whole, so code the demo did not reach but other levels
will (doors, lifts, other monsters) is not slowed down. Any other code section goes to FLASH unless it executed at least MIN_SHARE of the
demo's frame instructions; read-only data of non-core modules goes to flash too (the first build overflowed RAM with every non-core module
that ran at all kept whole). Usage: mksplit.py MAP PROFILE OUT.ld"""
import re, struct, sys, array, collections
mapf, proff, out = sys.argv[1:4]

HOT = re.compile(r"^(r_\w+|p_(?!saveg)\w+|v_video|z_zone|w_wad|m_fixed|m_random|m_bbox|tables|info|i_video|"
                 r"doomgeneric|hx_doom|hx_syscalls|hx_sound|hx_music|hx_stack|d_loop)\.o$")   # hx_sound: the audio callback runs in interrupt context
MIN_SHARE = 1e-5                                            # of all frame instructions (~1e9 over the profile): ~10k instructions
FLASH_ORIGIN, FLASH_LEN = 0x062A0000, 0x150000              # flash offset 0x2A0000-0x3EFFFF
RAM_ORIGIN, RAM_LEN = 0x02023000, 0x74000                   # borrowed static RAM (tested clean), to 0x02096FFF
RAM2_ORIGIN, RAM2_LEN = 0x020F5000, 0x14000                 # tested clean, to 0x02108FFF
BSS2 = ["openings", "viewangletox", "drawsegs", "zlight"]   # big renderer arrays moved to RAM2 (~76 KiB)

d = open(proff, "rb").read()
assert d[:4] == b"EMUP"
words = struct.unpack_from("<I", d, 8)[0]
frames = array.array("I"); frames.frombytes(d[12 + 4 * words:12 + 8 * words])
total = sum(frames)

secs = []                                                   # (addr, size, section, object)
lines = open(mapf).read().split("\n")
for i, l in enumerate(lines):
    m = re.match(r"^ (\.(?:text|rodata)\S*)\s+(0x[0-9a-f]+)\s+(0x[0-9a-f]+)\s+(\S+)", l)
    if not m:
        m2 = re.match(r"^ (\.(?:text|rodata)\S*)\s*$", l)
        if m2 and i + 1 < len(lines):
            nx = lines[i + 1].split()
            if len(nx) >= 3 and nx[0].startswith("0x"):
                secs.append((int(nx[0], 16), int(nx[1], 16), m2.group(1), nx[2]))
        continue
    secs.append((int(m.group(2), 16), int(m.group(3), 16), m.group(1), m.group(4)))

def pattern(obj):
    m = re.match(r".*/(lib\w+\.a)\((.+)\)$", obj)
    if m: return f"*{m.group(1)}:{m.group(2)}", m.group(2)
    return "*/" + obj.split("/")[-1], obj.split("/")[-1]

cold = collections.defaultdict(list)                       # pattern -> [section names]
stats = collections.Counter()
for a, sz, name, obj in secs:
    if not sz: continue
    pat, base = pattern(obj)
    if obj.endswith("crt0.o") or obj.endswith("crt0c.o"): continue
    hot_mod = bool(HOT.match(base))
    if name.startswith(".text"):
        ran = sum(frames[a >> 2:(a + sz) >> 2]) >= MIN_SHARE * total
        if not hot_mod and not ran: cold[pat].append(name); stats["flash text"] += sz
        else: stats["ram text"] += sz
    else:
        if not hot_mod: cold[pat].append(name); stats["flash rodata"] += sz
        else: stats["ram rodata"] += sz

ftext = "\n".join(f"    {pat}({' '.join(sorted(set(n)))})" for pat, n in sorted(cold.items()))
bss2 = " ".join(f"*(.bss.{s})" for s in BSS2)
open(out, "w").write(f"""/* Generated by doom/mksplit.py: Doom split between flash (cold, runs in place) and fixed RAM. Do not edit. */
ENTRY(hx_main)
MEMORY {{
  FLASH (rx) : ORIGIN = {FLASH_ORIGIN:#x}, LENGTH = {FLASH_LEN:#x}
  RAM (rwx)  : ORIGIN = {RAM_ORIGIN:#x}, LENGTH = {RAM_LEN:#x}
  RAM2 (rw)  : ORIGIN = {RAM2_ORIGIN:#x}, LENGTH = {RAM2_LEN:#x}
}}
SECTIONS {{
  .fhdr : {{ KEEP(*(.fhdr)) }} > FLASH
  .ftext : ALIGN(4) {{
{ftext}
  }} > FLASH
  .text : ALIGN(4) {{ __text_dst = .; *(.text .text.*) *(.rodata .rodata.*) . = ALIGN(4); __text_end = .; }} > RAM AT> FLASH
  __text_src = LOADADDR(.text);
  __text_len = __text_end - __text_dst;
  .data : ALIGN(4) {{ __data_dst = .; *(.data .data.* .sdata .sdata.*) . = ALIGN(4); __data_end = .; }} > RAM AT> FLASH
  __data_src = LOADADDR(.data);
  __data_len = __data_end - __data_dst;
  __flash_end = LOADADDR(.data) + SIZEOF(.data);
  .bss2 (NOLOAD) : ALIGN(4) {{ __bss2_start = .; {bss2} . = ALIGN(4); __bss2_end = .; }} > RAM2
  __bss2_len = __bss2_end - __bss2_start;
  .bss (NOLOAD) : ALIGN(4) {{ __bss_start = .; *(.bss .bss.* .sbss .sbss.* COMMON) . = ALIGN(4); __bss_end = .; }} > RAM
  __bss_len = __bss_end - __bss_start;
  /DISCARD/ : {{ *(.comment) *(.eh_frame) }}
}}
""")
print(f"{out}: " + ", ".join(f"{k} {v}" for k, v in sorted(stats.items())))
