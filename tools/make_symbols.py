"""Generate docs/config/symbols.txt: one line per function-start candidate in the code region of the flash dump.
Function starts = targets of l.jal that land on a stack-frame prologue; names are fn_<addr> unless evidence names them
(see KNOWN below). Strings referenced via movhi/ori constants are listed as comments: that is the main source of naming clues."""
import struct, re, collections, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, "firmware", "dump.bin"), "rb").read()[:0x400000]
BASE = 0x06000000
CODE_END = 0x7E000
w = struct.unpack("<%dI" % (CODE_END // 4), d[:CODE_END])

KNOWN = {  # address -> (name, evidence)
 0x06004480: ("dbg_printf", "takes a format string in r3 and varargs on the stack; 17 call sites in the code region incl. the [SD UPDATE] logs"),
 0x0600495C: ("sd_update_run", "references Xly100s.bin and the [SD UPDATE] strings; checks, then flashes"),
 0x06003BF0: ("spi_flash_erase_sector", "sends opcode 0x20 + address"),
 0x06003A7C: ("spi_flash_program", "loops 256-byte pages via 0x060039E8"),
 0x060039E8: ("spi_flash_page_program", "sends opcode 0x02 + address + 256 bytes"),
 0x06003E84: ("spi_flash_read", "sends opcode 0x03 + address"),
 0x06006DD8: ("spi_send_byte", "clears bit 0x80 of SPR 0x9000, writes the byte to SPR 0x9250, writes 1 to SPR 0x9244, polls bit 0 of SPR 0x9248 (raw disassembly; the decompiler hides the SPR accesses)"),
 0x06006FFC: ("spi_cs_ctrl", "takes 0/1: clears (0) or sets (1) bit 0x4000 of SPR 0x9000; called with 0 before and 1 after every SPI command (raw disassembly)"),
 0x0600481C: ("sd_update_read_chunk", "called as (buffer, 0x1000) at the top of the write loop; negative return -> error code R"),
}

def is_pro(o):
    if o < 0 or o + 8 > len(d): return False
    for k in (0, 4):
        x = struct.unpack_from("<I", d, o + k)[0]
        if (x >> 26) == 0x35 and ((x >> 16) & 31) == 1: return True
    return False

callers = collections.Counter()
for i, x in enumerate(w):
    if (x >> 26) == 1:
        imm = x & 0x3FFFFFF
        if imm & 0x2000000: imm -= 0x4000000
        t = i * 4 + imm * 4
        if 0x200 <= t < CODE_END and is_pro(t): callers[t] += 1
starts = sorted(set(callers) | {a - BASE for a in KNOWN if a - BASE < CODE_END})

def cstr(o):
    if not (0 <= o < 0x400000): return None
    e = d.find(b"\x00", o)
    s = d[o:e]
    return s.decode("latin1") if 4 <= len(s) <= 60 and all(32 <= c < 127 for c in s) else None

strs = collections.defaultdict(list)
regs = {}
for i, x in enumerate(w):
    if (x >> 26) == 6 and not (x >> 16) & 1: regs[(x >> 21) & 31] = (i, (x & 0xFFFF) << 16)
    elif (x >> 26) == 0x2A:
        rd, ra = (x >> 21) & 31, (x >> 16) & 31
        if rd == ra and ra in regs and i - regs[ra][0] <= 12:
            c = regs[ra][1] | (x & 0xFFFF)
            if BASE <= c < BASE + 0x400000:
                s = cstr(c - BASE)
                if s:
                    p = i * 4
                    import bisect
                    f = starts[bisect.bisect_right(starts, p) - 1] if starts and p >= starts[0] else None
                    if f is not None: strs[f].append(s.strip())

# Subsystem tags from the firmware's own debug-string prefixes (first match wins). Names are guesses, tagged "tag_" + address.
TAGS = [(r"\[SD UPDATE\]|sd_update|SD Update|CheckNeedUpdata|Xly100s", "sd_update"), (r"\[SD\]|<SD>|<MMC>|SD -CRC|sd capacity|sd speed|sd stat", "sd"),
        (r"\[DEV\]|battery|g-sensor|usb-dev|low power", "dev"), (r"gsensor|GMA301|SC7A30E", "gsensor"), (r"nvfs|NV JPG|FLASH CAP", "nvfs"),
        (r"fs :|f_write|EXFAT|MSDOS|open file|node err|fp->cltbl", "fatfs"), (r"\[Sensor|SENSOR|CSI_SEN|mipi_|rgbgamma|ygamma", "sensor"),
        (r"\[mjp|mjp Enc|DecodeAddToImg|\.jpg|\.avi|PICT", "jpeg_avi"), (r"lcd =|LCD|\[WIN\]", "ui"), (r"UVC|usb update|Mass-Storage|start usb", "usb"),
        (r"WDT|exception|low power", "sys")]
def tag_for(ss):
    import re as _re
    for pat, t in TAGS:
        if any(_re.search(pat, x) for x in ss): return t
    return None

with open(os.path.join(ROOT, "config", "symbols.txt"), "w") as out:
    out.write("# flash_addr  run_addr  size  name   ; region ; callers N ; evidence / strings   (generated by tools/make_symbols.py; do not edit by hand)\n")
    out.write("# run_addr: SUPERSEDED, do not use: it comes from an old address model (RAM-resident code at flash+0x0A002E00). The big body runs in place at 0x06000000+flash, and the in-place region (flash 0x2E00-0x13FFF) runs from a RAM copy at flash+0x01FFD200: see docs/hardware-and-firmware-guide.md section 1. Region labels are approximate.\n")
    for k, f in enumerate(starts):
        end = starts[k + 1] if k + 1 < len(starts) else CODE_END
        a = BASE + f
        ss = list(dict.fromkeys(strs.get(f, [])))[:3]
        tg = tag_for(ss)
        name, ev = KNOWN.get(a, (f"{tg}_{a:08x}" if tg else f"fn_{a:08x}", ""))
        note = ev or ("; ".join(repr(s) for s in ss))
        region = "in-place" if f < 0x14000 else "RAM-resident"
        run = a if f < 0x14000 else f + 0x0A002E00
        out.write(f"{a:#010x} {run:#010x} {end - f:#07x} {name} ; {region} ; callers {callers.get(f, 0)}" + (f" ; {note}" if note else "") + "\n")
print(len(starts), "function starts;", sum(1 for f in starts if strs.get(f)), "reference strings;", len(KNOWN), "named by evidence")
